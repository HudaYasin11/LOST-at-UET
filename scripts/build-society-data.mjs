// Rebuild the browser module after editing approved links or collecting artwork.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const socials = JSON.parse(fs.readFileSync(path.join(root, 'data/society-socials.json'), 'utf8'));
const artwork = JSON.parse(fs.readFileSync(path.join(root, 'assets/societies/sources.json'), 'utf8'));
for (const [id, record] of Object.entries(socials)) {
    for (const url of [record.instagram, ...record.links.map(link => link.url)].filter(Boolean)) {
        if (new URL(url).protocol !== 'https:') throw Error(`Non-HTTPS society link: ${id}`);
    }
    if (artwork[id]?.path) {
        if (!fs.existsSync(path.join(root, artwork[id].path))) throw Error(`Missing logo: ${id}`);
        record.logo = artwork[id].path;
        record.logoSource = artwork[id].source;
    }
    record.reviewedAt = '2026-09-10';
}
fs.writeFileSync(path.join(root, 'data/society-details.js'), '// Generated by scripts/build-society-data.mjs from user-approved sources.\nexport const societyDetails = ' + JSON.stringify(socials, null, 2) + ';\n');
console.log(`Prepared ${Object.keys(socials).length} society link records and ${Object.values(socials).filter(record => record.logo).length} logos.`);
